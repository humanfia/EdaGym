class QualificationFixtureSnapshot(StrictModel):
    schema_version: SchemaVersion = 1
    fixture_id: Identifier
    pair_id: Identifier
    tool_id: Identifier
    capability: Capability
    semantic_claim_id: Identifier
    semantic_joints: tuple[SemanticJoint, ...]
    role: FixtureRole
    rejection_reason: SemanticRejectionReason | None = None
    inputs: tuple[FixtureInputSnapshot, ...]
    restricted_assets: tuple[FixtureAssetInputSnapshot, ...] = Field(
        default=(),
        exclude_if=lambda value: not value,
    )
    invocations: tuple[FixtureInvocationSnapshot, ...]
    expected_exit_codes: tuple[int, ...]
    outputs: tuple[FixtureOutputSnapshot, ...]
    log_retention: Literal["full", "marker_projection"]
    retained_log_marker_digests: tuple[Digest, ...]
    parser_digest: Digest

    @field_validator("semantic_joints")
    @classmethod
    def normalize_claim_joints(
        cls,
        value: tuple[SemanticJoint, ...],
    ) -> tuple[SemanticJoint, ...]:
        if len(value) != len(set(value)):
            raise ValueError("qualification semantic joints must be unique")
        return tuple(sorted(value, key=lambda item: item.value))

    @model_validator(mode="after")
    def validate_contract(self) -> Self:
        if self.semantic_claim_id != claim_id_for_joints(
            self.capability,
            self.semantic_joints,
        ):
            raise ValueError("qualification semantic claim is not canonical")
        if self.pair_id != qualification_fixture_id(self.tool_id, self.capability):
            raise ValueError("qualification pair identity must be derived from tool capability")
        if self.fixture_id != qualification_case_id(
            self.tool_id,
            self.capability,
            self.role,
        ):
            raise ValueError("qualification case identity must include its evidence role")
        if (self.role is FixtureRole.REJECTION) != (self.rejection_reason is not None):
            raise ValueError("only rejection cases carry an expected semantic reason")
        if not self.inputs or not self.invocations:
            raise ValueError("qualification fixture snapshots require inputs and invocations")
        if (
            len(self.expected_exit_codes) != len(self.invocations)
            or any(
                isinstance(code, bool) or not isinstance(code, int) or code < 0 or code > 255
                for code in self.expected_exit_codes
            )
            or any(self.expected_exit_codes[:-1])
            or (self.role is FixtureRole.ACCEPTANCE and any(self.expected_exit_codes))
        ):
            raise ValueError("qualification exit codes must be role-bound completion statuses")
        input_ids = [item.logical_id for item in self.inputs]
        input_paths = [item.path for item in self.inputs]
        asset_ids = [item.logical_id for item in self.restricted_assets]
        asset_paths = [item.path for item in self.restricted_assets]
        output_ids = [item.logical_id for item in self.outputs]
        output_paths = [item.path for item in self.outputs]
        if len(input_ids) != len(set(input_ids)) or len(input_paths) != len(set(input_paths)):
            raise ValueError("qualification snapshot inputs must be unique")
        if len(asset_ids) != len(set(asset_ids)) or len(asset_paths) != len(set(asset_paths)):
            raise ValueError("qualification snapshot restricted assets must be unique")
        if len(output_ids) != len(set(output_ids)) or len(output_paths) != len(set(output_paths)):
            raise ValueError("qualification snapshot outputs must be unique")
        if (
            set(input_ids) & (set(asset_ids) | set(output_ids))
            or set(asset_ids) & set(output_ids)
            or set(input_paths) & (set(asset_paths) | set(output_paths))
            or set(asset_paths) & set(output_paths)
        ):
            raise ValueError("qualification snapshot input and output identities cannot overlap")
        generated = {
            item.executable
            for item in self.invocations
            if isinstance(item, WorkspaceInvocationSnapshot)
        }
        if not generated.issubset(set(output_paths)):
            raise ValueError("generated fixture programs must be declared as snapshot outputs")
        if (self.log_retention == "marker_projection") != bool(self.retained_log_marker_digests):
            raise ValueError("marker-projected logs require exact retained marker identities")
        return self

    @property
    def digest(self) -> str:
        return canonical_digest(self, domain="backend-qualification-fixture-v1")


