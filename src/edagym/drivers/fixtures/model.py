class FixtureParser(Protocol):
    """Judge tool semantics without relying on diagnostic wording alone."""

    def accepts(self, observation: FixtureObservation) -> bool: ...

    def rejection(
        self,
        observation: FixtureObservation,
    ) -> SemanticRejectionReason | None: ...


@dataclass(frozen=True, slots=True)
class MarkerParser:
    marker: bytes
    output_path: str | None = None
    output_token: bytes | None = None
    rejection_marker: bytes | None = None
    rejection_reason: SemanticRejectionReason | None = None
    rejection_exit_code: int = 0
    missing_output_token_rejection_reason: SemanticRejectionReason | None = None

    def __post_init__(self) -> None:
        if (self.rejection_marker is None) != (self.rejection_reason is None):
            raise ValueError("marker rejection requires both a marker and typed reason")
        if self.rejection_marker == self.marker:
            raise ValueError("acceptance and rejection markers must differ")
        if (
            isinstance(self.rejection_exit_code, bool)
            or not isinstance(self.rejection_exit_code, int)
            or self.rejection_exit_code < 0
            or self.rejection_exit_code > 255
        ):
            raise ValueError("semantic rejection exit code must be an unsigned process status")
        if self.missing_output_token_rejection_reason is not None and (
            self.output_path is None or self.output_token is None
        ):
            raise ValueError("missing-token rejection requires a declared output token")

    def accepts(self, observation: FixtureObservation) -> bool:
        if not observation.exit_codes or any(code != 0 for code in observation.exit_codes):
            return False
        if self.marker not in b"\n".join(observation.stdout):
            return False
        if self.rejection_marker is not None and self.rejection_marker in b"\n".join(
            (*observation.stdout, *observation.stderr)
        ):
            return False
        if self.output_path is None:
            return True
        output = observation.file(self.output_path)
        if output is None or output.truncated:
            return False
        return self.output_token is None or self.output_token in output.content

    def rejection(
        self,
        observation: FixtureObservation,
    ) -> SemanticRejectionReason | None:
        if (
            not observation.exit_codes
            or any(code != 0 for code in observation.exit_codes[:-1])
            or observation.exit_codes[-1] != self.rejection_exit_code
        ):
            return None
        streams = b"\n".join((*observation.stdout, *observation.stderr))
        if (
            self.rejection_marker is not None
            and self.rejection_reason is not None
            and self.rejection_marker in streams
            and self.marker not in streams
        ):
            return self.rejection_reason
        if (
            self.missing_output_token_rejection_reason is not None
            and self.marker in streams
            and self.output_path is not None
            and self.output_token is not None
        ):
            output = observation.file(self.output_path)
            if (
                output is not None
                and not output.truncated
                and self.output_token not in output.content
            ):
                return self.missing_output_token_rejection_reason
        return None


@dataclass(frozen=True, slots=True)
class MarkerSetParser:
    """Require independent semantic markers from one successful invocation."""

    markers: tuple[bytes, ...]
    rejection_markers: tuple[bytes, ...] = ()
    rejection_reason: SemanticRejectionReason | None = None

    def __post_init__(self) -> None:
        if len(self.markers) < 2 or len(self.markers) != len(set(self.markers)):
            raise ValueError("marker-set parsers require unique independent markers")
        if (not self.rejection_markers) != (self.rejection_reason is None):
            raise ValueError("marker-set rejection requires markers and a typed reason")
        if len(self.rejection_markers) != len(set(self.rejection_markers)):
            raise ValueError("marker-set rejection markers must be unique")
        if set(self.markers) & set(self.rejection_markers):
            raise ValueError("acceptance and rejection marker sets cannot overlap")

    def accepts(self, observation: FixtureObservation) -> bool:
        stdout = b"\n".join((*observation.stdout, *observation.stderr))
        return (
            observation.exit_codes == (0,)
            and all(marker in stdout for marker in self.markers)
            and not any(marker in stdout for marker in self.rejection_markers)
        )

    def rejection(
        self,
        observation: FixtureObservation,
    ) -> SemanticRejectionReason | None:
        streams = b"\n".join((*observation.stdout, *observation.stderr))
        if (
            observation.exit_codes == (0,)
            and self.rejection_reason is not None
            and all(marker in streams for marker in self.rejection_markers)
            and not any(marker in streams for marker in self.markers)
        ):
            return self.rejection_reason
        return None


@dataclass(frozen=True, slots=True)
class SemanticTokenParser:
    """Classify a completed workload from mutually exclusive semantic tokens."""

    completion_marker: bytes
    acceptance_token: bytes
    rejection_token: bytes
    rejection_reason: SemanticRejectionReason

    def __post_init__(self) -> None:
        values = (self.completion_marker, self.acceptance_token, self.rejection_token)
        if any(not value for value in values) or len(values) != len(set(values)):
            raise ValueError("semantic outcome tokens must be distinct and non-empty")

    def accepts(self, observation: FixtureObservation) -> bool:
        streams = b"\n".join((*observation.stdout, *observation.stderr))
        return (
            observation.exit_codes == (0,)
            and self.completion_marker in streams
            and self.acceptance_token in streams
            and self.rejection_token not in streams
        )

    def rejection(
        self,
        observation: FixtureObservation,
    ) -> SemanticRejectionReason | None:
        streams = b"\n".join((*observation.stdout, *observation.stderr))
        if (
            observation.exit_codes == (0,)
            and self.completion_marker in streams
            and self.rejection_token in streams
            and self.acceptance_token not in streams
        ):
            return self.rejection_reason
        return None


@dataclass(frozen=True, slots=True)
class YosysNetlistParser:
    marker: bytes
    output_path: str
    module_name: str

    def accepts(self, observation: FixtureObservation) -> bool:
        if observation.exit_codes != (0,) or self.marker not in b"\n".join(observation.stdout):
            return False
        output = observation.file(self.output_path)
        if output is None or output.truncated:
            return False
        try:
            document = json.loads(output.content)
            module = document["modules"][self.module_name]
            cells = module["cells"]
        except (KeyError, TypeError, json.JSONDecodeError, UnicodeDecodeError):
            return False
        return isinstance(cells, dict) and bool(cells)

    def rejection(
        self,
        observation: FixtureObservation,
    ) -> SemanticRejectionReason | None:
        if observation.exit_codes != (0,) or self.marker not in b"\n".join(observation.stdout):
            return None
        output = observation.file(self.output_path)
        if output is None or output.truncated:
            return None
        try:
            cells = json.loads(output.content)["modules"][self.module_name]["cells"]
        except (KeyError, TypeError, json.JSONDecodeError, UnicodeDecodeError):
            return None
        return (
            SemanticRejectionReason.DEGENERATE_IMPLEMENTATION
            if isinstance(cells, dict) and not cells
            else None
        )


@dataclass(frozen=True, slots=True)
class AbcSynthesisParser:
    marker: bytes
    output_path: str
    model_name: str

    def accepts(self, observation: FixtureObservation) -> bool:
        if observation.exit_codes != (0,) or self.marker not in b"\n".join(observation.stdout):
            return False
        output = observation.file(self.output_path)
        if output is None or output.truncated:
            return False
        lines = tuple(line.strip() for line in output.content.splitlines())
        logic_covers = [
            line for line in lines if line.startswith(b".names ") and len(line.split()) >= 3
        ]
        return (
            f".model {self.model_name}".encode() in lines
            and any(line.startswith(b".inputs ") for line in lines)
            and any(line.startswith(b".outputs ") for line in lines)
            and bool(logic_covers)
            and b".end" in lines
        )

    def rejection(
        self,
        observation: FixtureObservation,
    ) -> SemanticRejectionReason | None:
        if observation.exit_codes != (0,) or self.marker not in b"\n".join(observation.stdout):
            return None
        output = observation.file(self.output_path)
        if output is None or output.truncated:
            return None
        lines = tuple(line.strip() for line in output.content.splitlines())
        valid_shell = (
            f".model {self.model_name}".encode() in lines
            and any(line.startswith(b".inputs ") for line in lines)
            and any(line.startswith(b".outputs ") for line in lines)
            and b".end" in lines
        )
        has_logic_cover = any(
            line.startswith(b".names ") and len(line.split()) >= 3 for line in lines
        )
        if valid_shell and not has_logic_cover:
            return SemanticRejectionReason.DEGENERATE_IMPLEMENTATION
        return None


