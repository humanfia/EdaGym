def qualification_case_id(
    tool_id: str,
    capability: Capability,
    role: FixtureRole,
) -> str:
    """Derive the immutable identity of one role in a qualification pair."""

    return f"{qualification_fixture_id(tool_id, capability)}_{role.value}"


