_IDENTIFIER = re.compile(r"^[a-z][a-z0-9]*(?:[._-][a-z0-9]+)*$")


def _validate_identifier(value: str) -> None:
    if len(value) > 96 or _IDENTIFIER.fullmatch(value) is None:
        raise ValueError(f"invalid fixture identifier: {value!r}")


def qualification_artifact_id(fixture_id: str, local_id: str) -> str:
    """Derive a globally unique evidence identity from fixture-local names."""

    value = f"{fixture_id}.{local_id}"
    _validate_identifier(value)
    return value


