@dataclass(frozen=True, slots=True)
class VerilatorLintParser:
    output_path: str
    module_name: str
    rejection_marker: bytes = b"%Warning-LATCH:"

    def accepts(self, observation: FixtureObservation) -> bool:
        if not observation.exit_codes or any(observation.exit_codes):
            return False
        output = observation.file(self.output_path)
        if output is None or output.truncated:
            return False
        try:
            root = json.loads(output.content)
            modules = root["modulesp"]
        except (json.JSONDecodeError, KeyError, TypeError, UnicodeDecodeError):
            return False
        warnings = b"\n".join((*observation.stdout, *observation.stderr))
        return (
            self.rejection_marker not in warnings
            and isinstance(modules, list)
            and any(
                isinstance(module, dict) and module.get("origName") == self.module_name
                for module in modules
            )
        )

    def rejection(
        self,
        observation: FixtureObservation,
    ) -> SemanticRejectionReason | None:
        if not observation.exit_codes or any(observation.exit_codes):
            return None
        output = observation.file(self.output_path)
        if output is None or output.truncated:
            return None
        try:
            modules = json.loads(output.content)["modulesp"]
        except (json.JSONDecodeError, KeyError, TypeError, UnicodeDecodeError):
            return None
        streams = b"\n".join((*observation.stdout, *observation.stderr))
        if (
            self.rejection_marker in streams
            and isinstance(modules, list)
            and any(
                isinstance(module, dict) and module.get("origName") == self.module_name
                for module in modules
            )
        ):
            return SemanticRejectionReason.RULE_VIOLATION
        return None


@dataclass(frozen=True, slots=True)
class KlayoutDrcParser:
    output_path: str
    rule_id: str

    def _violation_count(self, observation: FixtureObservation) -> int | None:
        if observation.exit_codes != (0,):
            return None
        output = observation.file(self.output_path)
        if output is None or output.truncated:
            return None
        try:
            report = json.loads(output.content)
        except (json.JSONDecodeError, UnicodeDecodeError):
            return None
        if not isinstance(report, dict) or set(report) != {
            "engine",
            "engine_version",
            "minimum_spacing_nm",
            "rule_id",
            "violation_count",
        }:
            return None
        count = report["violation_count"]
        minimum = report["minimum_spacing_nm"]
        if (
            report["engine"] != "klayout.db"
            or report["rule_id"] != self.rule_id
            or not isinstance(report["engine_version"], str)
            or not report["engine_version"]
            or isinstance(minimum, bool)
            or not isinstance(minimum, int)
            or minimum <= 0
            or isinstance(count, bool)
            or not isinstance(count, int)
            or count < 0
        ):
            return None
        return int(count)

    def accepts(self, observation: FixtureObservation) -> bool:
        return self._violation_count(observation) == 0

    def rejection(
        self,
        observation: FixtureObservation,
    ) -> SemanticRejectionReason | None:
        count = self._violation_count(observation)
        if count is not None and count > 0:
            return SemanticRejectionReason.RULE_VIOLATION
        return None


