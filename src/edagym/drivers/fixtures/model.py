@dataclass(frozen=True, slots=True)
class MarkerLogProjection:
    """Retain exact public markers while discarding all surrounding diagnostics."""

    markers: tuple[bytes, ...]

    def __post_init__(self) -> None:
        if (
            not self.markers
            or len(self.markers) != len(set(self.markers))
            or any(not marker or len(marker) > 256 or b"\n" in marker for marker in self.markers)
        ):
            raise ValueError("retained log markers must be unique bounded single-line values")

    def project(self, chunks: Iterable[bytes]) -> bytes:
        found = [False] * len(self.markers)
        overlap = max(len(marker) for marker in self.markers) - 1
        tail = b""
        for chunk in chunks:
            window = tail + chunk
            for index, marker in enumerate(self.markers):
                found[index] |= marker in window
            tail = window[-overlap:] if overlap else b""
        return b"".join(
            marker + b"\n" for marker, present in zip(self.markers, found, strict=True) if present
        )


