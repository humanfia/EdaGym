@dataclass(frozen=True, slots=True)
class QualificationFixture:
    tool_id: str
    capability: Capability
    inputs: tuple[FixtureInput, ...]
    invocations: tuple[FixtureInvocation, ...]
    outputs: tuple[FixtureOutput, ...]
    parser: FixtureParser
    semantic_joints: tuple[SemanticJoint, ...] = ()
    restricted_assets: tuple[FixtureAssetInput, ...] = ()
    rejection_inputs: tuple[FixtureInput, ...] = ()
    rejection_reason: SemanticRejectionReason | None = None
    rejection_exit_code: int = 0
    log_projection: MarkerLogProjection | None = None

    def __post_init__(self) -> None:
        _validate_identifier(self.tool_id)
        if normalize_semantic_joints(self.capability, self.semantic_joints) != (
            self.semantic_joints
        ):
            raise ValueError("qualification semantic joints must use canonical order")
        if not self.inputs or not self.invocations:
            raise ValueError("qualification fixtures require inputs and invocations")
        input_ids = [item.logical_id for item in self.inputs]
        input_paths = [item.path for item in self.inputs]
        output_ids = [item.logical_id for item in self.outputs]
        output_paths = [item.path for item in self.outputs]
        asset_ids = [item.logical_id for item in self.restricted_assets]
        asset_paths = [item.path for item in self.restricted_assets]
        bound_asset_ids = [item.asset_id for item in self.restricted_assets]
        if len(input_ids) != len(set(input_ids)) or len(input_paths) != len(set(input_paths)):
            raise ValueError("qualification fixture inputs must be unique")
        if len(output_ids) != len(set(output_ids)) or len(output_paths) != len(set(output_paths)):
            raise ValueError("qualification fixture outputs must be unique")
        if (
            len(asset_ids) != len(set(asset_ids))
            or len(asset_paths) != len(set(asset_paths))
            or len(bound_asset_ids) != len(set(bound_asset_ids))
        ):
            raise ValueError("qualification fixture restricted assets must be unique")
        if (
            set(input_ids) & (set(asset_ids) | set(output_ids))
            or set(asset_ids) & set(output_ids)
            or set(input_paths) & (set(asset_paths) | set(output_paths))
            or set(asset_paths) & set(output_paths)
        ):
            raise ValueError("qualification inputs and outputs must be disjoint")
        if bool(self.rejection_inputs) != (self.rejection_reason is not None):
            raise ValueError("qualification rejection requires inputs and a typed reason")
        if (
            isinstance(self.rejection_exit_code, bool)
            or not isinstance(self.rejection_exit_code, int)
            or self.rejection_exit_code < 0
            or self.rejection_exit_code > 255
            or (not self.rejection_inputs and self.rejection_exit_code != 0)
        ):
            raise ValueError("semantic rejection exit code requires a paired fixture")
        if self.rejection_inputs:
            rejection_shape = tuple(
                (item.logical_id, item.path, item.media_type) for item in self.rejection_inputs
            )
            acceptance_shape = tuple(
                (item.logical_id, item.path, item.media_type) for item in self.inputs
            )
            if rejection_shape != acceptance_shape:
                raise ValueError("qualification pair must use one input topology")
            if all(
                rejected.content == accepted.content
                for accepted, rejected in zip(
                    self.inputs,
                    self.rejection_inputs,
                    strict=True,
                )
            ):
                raise ValueError("qualification rejection must change trusted input content")
        generated_programs = {
            item.executable for item in self.invocations if isinstance(item, WorkspaceInvocation)
        }
        if not generated_programs.issubset(set(output_paths)):
            raise ValueError("generated fixture programs must be declared as evidence outputs")

    @property
    def fixture_id(self) -> str:
        return qualification_fixture_id(self.tool_id, self.capability)

    @property
    def snapshot(self) -> QualificationFixtureSnapshot:
        return self.snapshot_for(FixtureRole.ACCEPTANCE)

    def snapshot_for(self, role: FixtureRole) -> QualificationFixtureSnapshot:
        inputs = self.inputs_for(role)
        case_id = qualification_case_id(self.tool_id, self.capability, role)
        return QualificationFixtureSnapshot(
            fixture_id=case_id,
            pair_id=self.fixture_id,
            tool_id=self.tool_id,
            capability=self.capability,
            semantic_claim_id=self.resolved_semantic_claim_id,
            semantic_joints=self.semantic_joints,
            role=role,
            rejection_reason=(self.rejection_reason if role is FixtureRole.REJECTION else None),
            inputs=tuple(
                FixtureInputSnapshot(
                    logical_id=qualification_artifact_id(case_id, item.logical_id),
                    path=item.path,
                    digest=_digest_bytes(item.content),
                    size_bytes=len(item.content),
                    media_type=item.media_type,
                )
                for item in inputs
            ),
            restricted_assets=tuple(
                FixtureAssetInputSnapshot(
                    logical_id=qualification_artifact_id(case_id, item.logical_id),
                    path=item.path,
                    asset_id=item.asset_id,
                    media_type=item.media_type,
                )
                for item in self.restricted_assets
            ),
            invocations=tuple(_invocation_snapshot(item) for item in self.invocations),
            expected_exit_codes=self.exit_codes_for(role),
            outputs=tuple(
                FixtureOutputSnapshot(
                    logical_id=qualification_artifact_id(case_id, item.logical_id),
                    path=item.path,
                    required=item.required,
                    media_type=item.media_type,
                )
                for item in self.outputs
            ),
            log_retention=("marker_projection" if self.log_projection is not None else "full"),
            retained_log_marker_digests=(
                tuple(_digest_bytes(marker) for marker in self.log_projection.markers)
                if self.log_projection is not None
                else ()
            ),
            parser_digest=canonical_digest(
                _parser_identity(self.parser),
                domain="backend-qualification-parser-v1",
            ),
        )

    @property
    def digest(self) -> str:
        if not self.rejection_inputs:
            return canonical_digest(
                {"acceptance": self.snapshot},
                domain="backend-qualification-pair-v1",
            )
        return canonical_digest(
            {
                "acceptance": self.snapshot_for(FixtureRole.ACCEPTANCE),
                "rejection": self.snapshot_for(FixtureRole.REJECTION),
            },
            domain="backend-qualification-pair-v1",
        )

    @property
    def resolved_semantic_claim_id(self) -> str:
        return claim_id_for_joints(self.capability, self.semantic_joints)

    def inputs_for(self, role: FixtureRole) -> tuple[FixtureInput, ...]:
        if role is FixtureRole.ACCEPTANCE:
            return self.inputs
        if not self.rejection_inputs:
            raise ValueError("qualification fixture has no rejection workload")
        return self.rejection_inputs

    def exit_codes_for(self, role: FixtureRole) -> tuple[int, ...]:
        final_code = self.rejection_exit_code if role is FixtureRole.REJECTION else 0
        return (0,) * (len(self.invocations) - 1) + (final_code,)


def _invocation_snapshot(invocation: FixtureInvocation) -> FixtureInvocationSnapshot:
    if isinstance(invocation, ToolInvocation):
        return ToolInvocationSnapshot(arguments=invocation.arguments)
    return WorkspaceInvocationSnapshot(
        executable=invocation.executable,
        arguments=invocation.arguments,
    )


def _parser_identity(parser: FixtureParser) -> dict[str, object]:
    identity_owner = getattr(parser, "qualification_identity", None)
    if identity_owner is not None:
        if not callable(identity_owner):
            raise TypeError("qualification parser identity owner must be callable")
        identity = identity_owner()
        if (
            not isinstance(identity, dict)
            or not identity
            or not isinstance(identity.get("kind"), str)
        ):
            raise TypeError("qualification parser identity must be a named mapping")
        _validate_identifier(identity["kind"])
        return identity
    if isinstance(parser, MarkerParser):
        return {
            "kind": "marker",
            "marker_digest": _digest_bytes(parser.marker),
            "output_path": parser.output_path,
            "output_token_digest": (
                _digest_bytes(parser.output_token) if parser.output_token is not None else None
            ),
            "rejection_marker_digest": (
                _digest_bytes(parser.rejection_marker)
                if parser.rejection_marker is not None
                else None
            ),
            "rejection_reason": parser.rejection_reason,
            "rejection_exit_code": parser.rejection_exit_code,
            "missing_output_token_rejection_reason": (parser.missing_output_token_rejection_reason),
        }
    if isinstance(parser, MarkerSetParser):
        return {
            "kind": "marker_set",
            "marker_digests": tuple(_digest_bytes(marker) for marker in parser.markers),
            "rejection_marker_digests": tuple(
                _digest_bytes(marker) for marker in parser.rejection_markers
            ),
            "rejection_reason": parser.rejection_reason,
        }
    if isinstance(parser, SemanticTokenParser):
        return {
            "kind": "semantic_token",
            "completion_marker_digest": _digest_bytes(parser.completion_marker),
            "acceptance_token_digest": _digest_bytes(parser.acceptance_token),
            "rejection_token_digest": _digest_bytes(parser.rejection_token),
            "rejection_reason": parser.rejection_reason,
        }
    if isinstance(parser, YosysNetlistParser):
        return {
            "kind": "yosys_netlist",
            "marker_digest": _digest_bytes(parser.marker),
            "output_path": parser.output_path,
            "module_name": parser.module_name,
            "rejection_reason": SemanticRejectionReason.DEGENERATE_IMPLEMENTATION,
        }
    if isinstance(parser, AbcSynthesisParser):
        return {
            "kind": "abc_synthesis",
            "marker_digest": _digest_bytes(parser.marker),
            "output_path": parser.output_path,
            "model_name": parser.model_name,
            "rejection_reason": SemanticRejectionReason.DEGENERATE_IMPLEMENTATION,
        }
    if isinstance(parser, AbcEquivalenceParser):
        return {
            "kind": "abc_equivalence",
            "marker_digest": _digest_bytes(parser.marker),
            "equivalence_token_digest": _digest_bytes(parser.equivalence_token),
            "mismatch_token_digest": _digest_bytes(parser.mismatch_token),
            "rejection_reason": SemanticRejectionReason.EQUIVALENCE_MISMATCH,
        }
    if isinstance(parser, YosysEquivalenceParser):
        return {
            "kind": "yosys_equivalence",
            "marker_digest": _digest_bytes(parser.marker),
            "proven_token_digest": _digest_bytes(parser.proven_token),
            "mismatch_token_digest": _digest_bytes(parser.mismatch_token),
            "rejection_reason": SemanticRejectionReason.EQUIVALENCE_MISMATCH,
        }
    if isinstance(parser, FirtoolLoweringParser):
        return {
            "kind": "firtool_lowering",
            "output_path": parser.output_path,
            "module_declaration_digest": _digest_bytes(parser.module_declaration),
            "sequential_token_digest": _digest_bytes(parser.sequential_token),
            "rejection_reason": SemanticRejectionReason.MISSING_REQUIRED_STRUCTURE,
        }
    if isinstance(parser, VerilatorLintParser):
        return {
            "kind": "verilator_lint",
            "output_path": parser.output_path,
            "module_name": parser.module_name,
            "rejection_marker_digest": _digest_bytes(parser.rejection_marker),
            "rejection_reason": SemanticRejectionReason.RULE_VIOLATION,
        }
    if isinstance(parser, KlayoutDrcParser):
        return {
            "kind": "klayout_drc",
            "output_path": parser.output_path,
            "rule_id": parser.rule_id,
            "rejection_reason": SemanticRejectionReason.RULE_VIOLATION,
        }
    if isinstance(parser, JasperPropertyStatusParser):
        return {
            "kind": "jasper_property_status",
            "property_name": parser.property_name,
            "expected_status_digest": _digest_bytes(parser.expected_status),
            "rejection_status_digest": _digest_bytes(parser.rejection_status),
            "rejection_reason": SemanticRejectionReason.PROPERTY_COUNTEREXAMPLE,
        }
    if isinstance(parser, JasperCdcStatusParser):
        return {
            "kind": "jasper_cdc_status",
            "expected_violation_count": parser.expected_violation_count,
            "pass_marker_digest": _digest_bytes(parser.pass_marker),
            "rejection_reason": SemanticRejectionReason.RULE_VIOLATION,
        }
    if isinstance(parser, SpyglassStatusParser):
        return {
            "kind": "spyglass_status",
            "status_marker_digest": _digest_bytes(parser.status_marker),
            "rejection_marker_digest": _digest_bytes(parser.rejection_marker),
            "rejection_reason": SemanticRejectionReason.RULE_VIOLATION,
        }
    raise TypeError("qualification parser has no canonical identity")


def _digest_bytes(value: bytes) -> str:
    return f"sha256:{hashlib.sha256(value).hexdigest()}"


def _validate_arguments(arguments: tuple[str, ...]) -> None:
    if any("\x00" in item or "\n" in item or "\r" in item for item in arguments):
        raise ValueError("qualification command arguments cannot contain control boundaries")


def _validate_media_type(value: str) -> None:
    if not value or len(value) > 127 or "\n" in value or "\r" in value:
        raise ValueError("qualification artifact media types must be normalized")
